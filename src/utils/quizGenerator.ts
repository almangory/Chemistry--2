/**
 * Robustly retrieves up to 30 unique, curriculum-aligned, non-repeating chemistry questions
 * based on selected unit, lesson, or favorite lessons list.
 */
export const generateQuizQuestions = (
  selectedUnitId: string,
  selectedLessonId: string | null,
  scope: "unit" | "lesson" | "favorites",
  favoriteLessons: string[],
  requestedCount: number
): QuizQuestion[] => {
  let pool: QuizQuestion[] = [];

  // 1. Gather all baseline handcrafted questions from quizzesData matching the criteria
  quizzesData.forEach((unitQuiz) => {
    // Add lessonId to baseline questions if not present based on question ID prefixes
    const mappedQuestions = unitQuiz.questions.map((q) => {
      let lessonId = q.lessonId;
      if (!lessonId) {
        // Map baseline IDs to logical lesson IDs
        if (unitQuiz.unitId === "1") {
          lessonId = q.id === "u1_q4" || q.id === "u1_q5" || q.id === "u1_q6" ? "u1_l3" : "u1_l1";
        } else if (unitQuiz.unitId === "2") {
          lessonId = q.id === "u2_q1" || q.id === "u2_q2" ? "u2_l1" : "u2_l2";
        } else if (unitQuiz.unitId === "3") {
          if (q.id === "u3_q1" || q.id === "u3_q2") lessonId = "u3_l1";
          else if (q.id === "u3_q3" || q.id === "u3_q4") lessonId = "u3_l2";
          else if (q.id === "u3_q5") lessonId = "u3_l7";
          else if (q.id === "u3_q6") lessonId = "u3_l4";
        } else if (unitQuiz.unitId === "4") {
          if (q.id === "u4_q1") lessonId = "u4_l1";
          else if (q.id === "u4_q2" || q.id === "u4_q3") lessonId = "u4_l2";
          else if (q.id === "u4_q4") lessonId = "u4_l3";
          else if (q.id === "u4_q5") lessonId = "u4_l4";
        } else if (unitQuiz.unitId === "5") {
          if (q.id === "u5_q1") lessonId = "u5_l1";
          else if (q.id === "u5_q2" || q.id === "u5_q3" || q.id === "u5_q5") lessonId = "u5_l2";
          else if (q.id === "u5_q4") lessonId = "u5_l3";
        } else if (unitQuiz.unitId === "6") {
          if (q.id === "u6_q1" || q.id === "u6_q2" || q.id === "u6_q3") lessonId = "u6_l1";
          else if (q.id === "u6_q4" || q.id === "u6_q5") lessonId = "u6_l2";
        }
      }
      return { ...q, lessonId: lessonId || `u${unitQuiz.unitId}_l1` };
    });

    // Filter by Scope
    if (scope === "unit" && unitQuiz.unitId === selectedUnitId) {
      pool.push(...mappedQuestions);
    } else if (scope === "lesson" && unitQuiz.unitId === selectedUnitId) {
      pool.push(...mappedQuestions.filter((q) => q.lessonId === selectedLessonId));
    } else if (scope === "favorites") {
      pool.push(...mappedQuestions.filter((q) => q.lessonId && favoriteLessons.includes(q.lessonId)));
    }
  });

  // 2. Gather from the extensive extra questions pool
  if (scope === "unit") {
    const extras = extraQuestionsPool[selectedUnitId] || [];
    pool.push(...extras);
  } else if (scope === "lesson") {
    const extras = (extraQuestionsPool[selectedUnitId] || []).filter((q) => q.lessonId === selectedLessonId);
    pool.push(...extras);
  } else if (scope === "favorites") {
    Object.keys(extraQuestionsPool).forEach((uId) => {
      const extras = extraQuestionsPool[uId].filter((q) => q.lessonId && favoriteLessons.includes(q.lessonId));
      pool.push(...extras);
    });
  }

  // 3. Remove duplicate questions by ID or question text to guarantee absolute uniqueness
  const uniqueQuestionsMap = new Map<string, QuizQuestion>();
  pool.forEach((q) => {
    if (!uniqueQuestionsMap.has(q.question)) {
      uniqueQuestionsMap.set(q.question, q);
    }
  });
  let uniquePool = Array.from(uniqueQuestionsMap.values());

  // 4. Shuffle the pool to make each quiz attempt fresh and fun
  uniquePool = uniquePool.sort(() => 0.5 - Math.random());

  // 5. Slice to the requested count (guaranteed maximum of 30)
  const finalCount = Math.min(requestedCount, 30, uniquePool.length);
  
  // Handle edge case where requestedCount is greater than available unique questions
  // (e.g., if there are only 12 questions in favorites, we return 12 unique questions without duplicating)
  return uniquePool.slice(0, finalCount);
};
